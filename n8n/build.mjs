#!/usr/bin/env node
/**
 * Builds n8n/workflows/*.json from n8n/workflows-src/*.mjs.
 * Each Code node names an entry function (workflows-src/code/*.js); esbuild bundles that function and
 * the n8n/src modules it uses into one self-contained script (no require/import at runtime), so the
 * Code node runs on any n8n with JS task runners and no NODE_FUNCTION_ALLOW_* settings.
 *
 *   node n8n/build.mjs            write the JSON files
 *   node n8n/build.mjs --check    fail if the committed JSON is out of date
 */
import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { canvas } from './workflows-src/lib/canvas.mjs';
import { assertEdges, connectionsFrom, resolveEdges } from './workflows-src/lib/graph.mjs';
import { stableUuid, workflowPlaceholder } from './workflows-src/lib/nodes.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, 'workflows');
const ENTRY_FILES = ['code/settings.js', 'code/summary.js', 'code/status.js', 'code/approve.js'].map((f) => join(HERE, 'workflows-src', f));
/**
 * Build and deploy order. A workflow another one names (error workflow, sub-workflow) comes first, so
 * deploy.mjs knows its id, and it is published before anything can call it.
 */
export const WORKFLOW_SOURCES = ['error-handler', 'deliver-email', 'write-draft', 'royalty-summary', 'job-status', 'sweeper', 'approve-draft'];
export const SETTINGS = Object.freeze({
  executionOrder: 'v1', saveDataErrorExecution: 'all', saveDataSuccessExecution: 'all',
  saveManualExecutions: true, callerPolicy: 'workflowsFromSameOwner',
});

async function entryFileFor(entry) {
  for (const file of ENTRY_FILES) {
    const mod = await import(pathToFileURL(file).href);
    if (typeof mod[entry] === 'function') return file;
  }
  throw new Error(`No Code-node entry named "${entry}" in ${ENTRY_FILES.join(', ')}`);
}

/**
 * @returns {Promise<string>} IIFE that stores the entry function in the in-scope `__bookleaf` object.
 * (Not esbuild's globalName: its getter-based exports come out empty inside n8n's task-runner sandbox.)
 */
async function bundle(entry) {
  const file = await entryFileFor(entry);
  const r = await build({
    stdin: { contents: `import { ${entry} as main } from ${JSON.stringify(file)};\n__bookleaf.main = main;`, resolveDir: HERE, loader: 'js' },
    bundle: true, write: false, format: 'iife', platform: 'neutral',
    target: 'es2022', legalComments: 'none', charset: 'utf8', logLevel: 'silent',
  });
  const text = r.outputFiles[0].text;
  // A module namespace object (`import * as x` used dynamically) relies on getters that come out
  // empty in n8n's task-runner sandbox; fail the build instead of failing at run time.
  if (/__export\(/.test(text)) throw new Error(`Code-node entry "${entry}" bundles a module namespace object; import named functions instead`);
  return text;
}

/** Code node script: the node's own logic first (readable in the n8n editor), the bundled library after. */
async function jsCodeFor(n) {
  const lib = await bundle(n.entry);
  return [
    `// BookLeaf: generated by n8n/build.mjs. Logic: n8n/src (entry "${n.entry}"). Edit the source and rebuild;`,
    '// do not edit this node by hand.',
    `const run = (main) => {\n${n.body}\n};`,
    '// ---- bundled from n8n/src ----',
    'const __bookleaf = {};',
    lib.trim(),
    'return run(__bookleaf.main);',
  ].join('\n');
}

const nodeId = (wf, name) => stableUuid(`${wf}/${name}`);

export async function buildWorkflow(srcName) {
  const src = (await import(pathToFileURL(join(HERE, 'workflows-src', `${srcName}.mjs`)).href)).default;
  assertEdges(src.nodes, src.edges);
  const edges = resolveEdges(src.nodes, src.edges);
  const nodes = [];
  for (const n of canvas(src)) {
    const { entry, body, ...rest } = n;
    const parameters = entry ? { ...rest.parameters, jsCode: await jsCodeFor(n) } : rest.parameters;
    nodes.push({ id: nodeId(srcName, n.name), ...rest, parameters });
  }
  const settings = { ...SETTINGS, ...src.settings, ...(src.errorWorkflow ? { errorWorkflow: workflowPlaceholder(src.errorWorkflow) } : {}) };
  return { name: src.name, nodes, connections: connectionsFrom(edges), settings };
}

async function main() {
  const check = process.argv.includes('--check');
  mkdirSync(OUT, { recursive: true });
  const stale = [];
  for (const name of WORKFLOW_SOURCES) {
    const json = `${JSON.stringify(await buildWorkflow(name), null, 2)}\n`;
    const path = join(OUT, `${name}.json`);
    if (check) {
      if (!existsSync(path) || readFileSync(path, 'utf8') !== json) stale.push(path);
    } else {
      writeFileSync(path, json);
      console.log(`built ${path} (${(json.length / 1024).toFixed(0)} KB)`);
    }
  }
  if (stale.length) throw new Error(`Out of date (run node n8n/build.mjs): ${stale.join(', ')}`);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((e) => {
    console.error(`build failed: ${e.message}`);
    process.exit(1);
  });
}
